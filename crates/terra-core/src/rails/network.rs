use super::*;
use std::cmp::Reverse;
use std::collections::{BTreeMap, BTreeSet, BinaryHeap};
use std::fmt;

pub const DISTANCE_SCALE: u64 = 1024;
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
pub struct Endpoint {
    pub anchor: [i64; 3],
    pub port: u8,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RailError {
    InvalidPiece,
    DuplicateAnchor,
    CapacityReached,
    AmbiguousConnection,
    UnknownEndpoint,
    Disconnected,
    BudgetExceeded,
}
impl fmt::Display for RailError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(match self {
            Self::InvalidPiece => "Invalid rail piece or pose.",
            Self::DuplicateAnchor => "A rail module already occupies this anchor.",
            Self::CapacityReached => "The rail network has reached its piece limit.",
            Self::AmbiguousConnection => {
                "More than one rail module uses the same directed connection."
            }
            Self::UnknownEndpoint => "The rail endpoint does not exist.",
            Self::Disconnected => "No active rail route connects these endpoints.",
            Self::BudgetExceeded => "The bounded rail search budget was exhausted.",
        })
    }
}
impl std::error::Error for RailError {}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct RouteLeg {
    pub anchor: [i64; 3],
    pub path: u8,
    pub reversed: bool,
}
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Route {
    pub endpoints: Vec<Endpoint>,
    pub legs: Vec<RouteLeg>,
    pub distance_units: u64,
}
impl Route {
    pub fn length(&self) -> f64 {
        self.distance_units as f64 / DISTANCE_SCALE as f64
    }
}

/// Reconstructible index over immutable piece records; no chunk is generated by routing.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct RouteNetwork {
    pieces: BTreeMap<[i64; 3], Piece>,
    ports: BTreeMap<Endpoint, Port>,
    connections: BTreeMap<(FixedPoint, [i16; 3]), Vec<Endpoint>>,
}
fn connection_key(port: Port) -> (FixedPoint, [i16; 3]) {
    let negative = port
        .tangent
        .iter()
        .find(|value| **value != 0)
        .is_some_and(|value| *value < 0);
    (
        port.position,
        if negative {
            port.tangent.map(|value| -value)
        } else {
            port.tangent
        },
    )
}
impl RouteNetwork {
    pub fn from_pieces(pieces: impl IntoIterator<Item = Piece>) -> Result<Self, RailError> {
        let mut network = Self::default();
        for piece in pieces {
            network.insert(piece)?;
        }
        Ok(network)
    }
    pub fn records(&self) -> impl ExactSizeIterator<Item = &Piece> {
        self.pieces.values()
    }
    pub fn get(&self, anchor: [i64; 3]) -> Option<&Piece> {
        self.pieces.get(&anchor)
    }
    pub fn len(&self) -> usize {
        self.pieces.len()
    }
    pub fn is_empty(&self) -> bool {
        self.pieces.is_empty()
    }
    /// Validate all new ports before changing either index.
    pub fn insert(&mut self, piece: Piece) -> Result<(), RailError> {
        if !piece.valid() {
            return Err(RailError::InvalidPiece);
        }
        if self.pieces.contains_key(&piece.anchor) {
            return Err(RailError::DuplicateAnchor);
        }
        if self.pieces.len() >= MAX_PIECES {
            return Err(RailError::CapacityReached);
        }
        let ports = piece.ports();
        for port in &ports {
            if !port.connectable {
                continue;
            }
            if let Some(existing) = self.connections.get(&connection_key(*port))
                && (existing.len() >= 2
                    || existing
                        .iter()
                        .any(|endpoint| !port.connects(self.ports[endpoint])))
            {
                return Err(RailError::AmbiguousConnection);
            }
        }
        for port in ports {
            let endpoint = Endpoint {
                anchor: piece.anchor,
                port: port.index,
            };
            if port.connectable {
                let connections = self.connections.entry(connection_key(port)).or_default();
                connections.push(endpoint);
                connections.sort_unstable();
            }
            self.ports.insert(endpoint, port);
        }
        self.pieces.insert(piece.anchor, piece);
        Ok(())
    }
    pub fn remove(&mut self, anchor: [i64; 3]) -> Option<Piece> {
        let piece = self.pieces.remove(&anchor)?;
        for port in piece.ports() {
            let endpoint = Endpoint {
                anchor,
                port: port.index,
            };
            self.ports.remove(&endpoint);
            let key = connection_key(port);
            if let Some(endpoints) = self.connections.get_mut(&key) {
                endpoints.retain(|entry| *entry != endpoint);
                if endpoints.is_empty() {
                    self.connections.remove(&key);
                }
            }
        }
        Some(piece)
    }
    /// A switch only selects an existing path; endpoint positions never change.
    pub fn set_switched(&mut self, anchor: [i64; 3], switched: bool) -> Result<(), RailError> {
        let piece = self
            .pieces
            .get_mut(&anchor)
            .ok_or(RailError::InvalidPiece)?;
        if switched && !piece.kind().is_some_and(Kind::is_switch) {
            return Err(RailError::InvalidPiece);
        }
        piece.switched = switched;
        Ok(())
    }
    pub fn port(&self, endpoint: Endpoint) -> Option<Port> {
        self.ports.get(&endpoint).copied()
    }
    pub fn connected_endpoint(&self, endpoint: Endpoint) -> Option<Endpoint> {
        let port = self.port(endpoint)?;
        self.connections
            .get(&connection_key(port))?
            .iter()
            .copied()
            .find(|other| *other != endpoint && port.connects(self.ports[other]))
    }
    /// Bounded by MAX_PIECES × four ports, with stable endpoint tie breaking.
    pub fn nearest_endpoint(&self, position: [f64; 3], max_distance: f64) -> Option<Endpoint> {
        if position.iter().any(|value| !value.is_finite())
            || !max_distance.is_finite()
            || max_distance < 0.0
        {
            return None;
        }
        let maximum_squared = max_distance * max_distance;
        let mut best: Option<(f64, Endpoint)> = None;
        for (&endpoint, port) in &self.ports {
            let point = port.position.position();
            let squared = (0..3)
                .map(|axis| (point[axis] - position[axis]).powi(2))
                .sum::<f64>();
            if squared <= maximum_squared
                && best.is_none_or(|(distance, previous)| {
                    squared < distance || squared == distance && endpoint < previous
                })
            {
                best = Some((squared, endpoint));
            }
        }
        best.map(|(_, endpoint)| endpoint)
    }
    /// Dijkstra traverses only complete active paths and exact opposite ports.
    /// Crossings never expose an edge between their perpendicular tracks.
    pub fn route(
        &self,
        start: Endpoint,
        goal: Endpoint,
        budget: usize,
    ) -> Result<Route, RailError> {
        if !self.ports.contains_key(&start) || !self.ports.contains_key(&goal) {
            return Err(RailError::UnknownEndpoint);
        }
        if budget == 0 {
            return Err(RailError::BudgetExceeded);
        }
        let budget = budget.min(MAX_ROUTE_VISITS);
        let mut queue = BinaryHeap::from([Reverse((0_u64, start))]);
        let mut distances = BTreeMap::from([(start, 0_u64)]);
        let mut previous: BTreeMap<Endpoint, (Endpoint, Option<RouteLeg>)> = BTreeMap::new();
        let mut visited = BTreeSet::new();
        while let Some(Reverse((distance, endpoint))) = queue.pop() {
            if visited.contains(&endpoint) {
                continue;
            }
            if visited.len() >= budget {
                return Err(RailError::BudgetExceeded);
            }
            visited.insert(endpoint);
            if endpoint == goal {
                let mut endpoints = vec![goal];
                let mut legs = Vec::new();
                let mut cursor = goal;
                while cursor != start {
                    let (parent, leg) = previous[&cursor];
                    if let Some(leg) = leg {
                        legs.push(leg);
                    }
                    endpoints.push(parent);
                    cursor = parent;
                }
                endpoints.reverse();
                legs.reverse();
                return Ok(Route {
                    endpoints,
                    legs,
                    distance_units: distance,
                });
            }
            let mut neighbors = Vec::new();
            if let Some(other) = self.connected_endpoint(endpoint) {
                neighbors.push((other, 0, None));
            }
            let piece = self.pieces[&endpoint.anchor];
            for path in piece.active_paths() {
                let reversed = path.ports[1] == endpoint.port;
                if !reversed && path.ports[0] != endpoint.port {
                    continue;
                }
                let other = Endpoint {
                    anchor: endpoint.anchor,
                    port: path.ports[usize::from(!reversed)],
                };
                let cost = (path.length() * DISTANCE_SCALE as f64).round().max(1.0) as u64;
                neighbors.push((
                    other,
                    cost,
                    Some(RouteLeg {
                        anchor: piece.anchor,
                        path: path.index,
                        reversed,
                    }),
                ));
            }
            neighbors.sort_by_key(|(endpoint, _, _)| *endpoint);
            for (other, cost, leg) in neighbors {
                let total = distance
                    .checked_add(cost)
                    .ok_or(RailError::BudgetExceeded)?;
                if distances.get(&other).is_none_or(|known| total < *known) {
                    distances.insert(other, total);
                    previous.insert(other, (endpoint, leg));
                    queue.push(Reverse((total, other)));
                }
            }
        }
        Err(RailError::Disconnected)
    }
}
